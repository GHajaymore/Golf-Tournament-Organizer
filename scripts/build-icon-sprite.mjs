/**
 * Build the icon sprite from the icons this app actually uses.
 *
 * The app drew its icons with a webfont: `@phosphor-icons/web`, two weights,
 * 272.6 KB of woff2 for about 120 glyphs out of roughly 1,500. It was also
 * `font-display: block`, so every icon in the product was INVISIBLE until that
 * font arrived. A sprite of only the icons in use is 13.2 KB brotli — a 259 KB
 * cut on the two largest assets in the app, and nothing to wait for.
 *
 * WHY THE OUTPUT IS COMMITTED rather than generated during `next build`:
 * a build step that must run before the compiler is a build step that will
 * eventually not run — in a Docker layer, in the Electron bundle, in whatever
 * comes next. A committed file is just source. It can go stale, and
 * `icon-sprite.test.ts` is what makes staleness loud: it re-derives the set of
 * names from source and fails if the sprite does not contain them.
 *
 * `@phosphor-icons/core` is a devDependency for the same reason — the SVGs are
 * read here, at authoring time, and never shipped.
 *
 * Run: node scripts/build-icon-sprite.mjs
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";

const CORE = "node_modules/@phosphor-icons/core/assets";
const OUT = "src/components/IconSprite.tsx";

/**
 * Every icon named anywhere in `src`, as `weight/name`.
 *
 * Scans for the two spellings that reach this app: the legacy class pair the
 * webfont used (`ph ph-eye`, `ph-fill ph-microphone`), which is still how icon
 * names are carried in DATA — `nav.ts` stores `icon: "ph ph-squares-four"` on
 * every entry — and the bare `name="eye"` the component takes.
 *
 * A name that is BUILT rather than written cannot be found by this and would
 * ship as a blank square. There is deliberately no such name left in the
 * codebase: `ThemePicker` used to compose one and now reads a literal map, so
 * the scan below is complete rather than nearly complete. Keep it that way —
 * `icon-sprite.test.ts` fails on any `ph-` token it cannot resolve, which is
 * the closest a test can get to enforcing it.
 */
export function usedIcons(root = "src") {
  const out = new Set();

  for (const file of sourceFiles(root)) {
    const src = readFileSync(file, "utf8");

    // The legacy class pair, which is still how icon names are carried in DATA.
    for (const m of src.matchAll(/\bph(-fill|-bold)? ph-([a-z0-9-]+)/g)) {
      out.add(`${m[1] ? m[1].slice(1) : "regular"}/${m[2]}`);
    }
    // The component's own spelling.
    for (const m of src.matchAll(/<Icon\s+name="([a-z0-9-]+)"(?:\s+weight="(fill|bold)")?/g)) {
      out.add(`${m[2] ?? "regular"}/${m[1]}`);
    }
  }

  return [...out].sort();
}

/**
 * Every .ts/.tsx under `root`, walked in Node rather than shelled out to grep.
 *
 * The first version ran `grep -rhoE`, which is fine on the Linux runner and
 * fine under Git Bash, and breaks on Windows the moment the pattern needs a
 * quote — `execSync` hands the string to cmd.exe, which has its own ideas
 * about quoting. A generator that only runs on some of the machines that need
 * it is a generator whose output goes stale on the others.
 */
function sourceFiles(root) {
  const found = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const path = `${root}/${entry.name}`;
    if (entry.isDirectory()) found.push(...sourceFiles(path));
    else if (/\.tsx?$/.test(entry.name)) found.push(path);
  }
  return found;
}

/** Where `@phosphor-icons/core` keeps a given weight+name. */
export function assetPath(key) {
  const [weight, name] = key.split("/");
  // Regular is the bare name; every other weight suffixes itself.
  return weight === "regular" ? `${CORE}/regular/${name}.svg` : `${CORE}/${weight}/${name}-${weight}.svg`;
}

/** `weight/name` → the sprite's symbol id. */
export const symbolId = (key) => `i-${key.replace("/", "-")}`;

function main() {
  const keys = usedIcons();
  const symbols = [];
  const missing = [];

  for (const key of keys) {
    const file = assetPath(key);
    if (!existsSync(file)) {
      missing.push(key);
      continue;
    }
    const svg = readFileSync(file, "utf8");
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .trim();
    symbols.push(`<symbol id="${symbolId(key)}" viewBox="0 0 256 256">${inner}</symbol>`);
  }

  if (missing.length) {
    console.error(`Not in @phosphor-icons/core:\n  ${missing.join("\n  ")}`);
    process.exit(1);
  }

  const body = symbols.join("");
  writeFileSync(
    OUT,
    `// GENERATED by scripts/build-icon-sprite.mjs — do not edit.
//
// The ${keys.length} icons this app uses, and only those. Re-run the script
// after adding an icon; \`icon-sprite.test.ts\` fails if this is stale.
//
// Rendered once, in the root layout, and referenced by <Icon> through
// <use href="#id">. Inline rather than an external /icons.svg because an
// external <use> is the feature that works until it doesn't — and because the
// font it replaces was \`font-display: block\`, so icons were invisible until
// 272.6 KB arrived. This has nothing to wait for.

/** Every symbol, hidden. Mounted once by the root layout. */
export function IconSprite() {
  return (
    <svg
      aria-hidden
      // Not \`display: none\`: Safari has historically dropped <use> references
      // into a fully hidden subtree. Zero-sized and clipped is the shape that
      // is safe everywhere.
      style={{ position: "absolute", width: 0, height: 0, overflow: "hidden" }}
      dangerouslySetInnerHTML={{ __html: ${JSON.stringify(body)} }}
    />
  );
}
`,
    "utf8",
  );

  const bytes = Buffer.byteLength(body);
  console.log(`${keys.length} icons → ${OUT} (${(bytes / 1024).toFixed(1)} KB raw)`);
}

if (import.meta.url === `file://${process.argv[1].split("\\").join("/")}` || process.argv[1]?.endsWith("build-icon-sprite.mjs")) {
  main();
}
